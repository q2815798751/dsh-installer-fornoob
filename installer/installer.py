def _project_root() -> str:
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _resource_dir() -> str:
    if getattr(sys, "frozen", False):
        return getattr(sys, "_MEIPASS", os.path.dirname(sys.executable))
    return os.path.join(_project_root(), "payload")


def _resource(name: str) -> str:
    return os.path.join(_resource_dir(), name)


def resources() -> dict:
    """All payload paths, with dev-mode fallbacks into the source tree."""
    root = _project_root()
    return {
        "node_zip": _resource("node-v24.18.0-win-x64.zip"),
        "launcher_exe": _resource("DSHLauncher.exe"),
        "icon": _resource("icon.ico"),
        "make_shortcut_ps1": _resource("make-shortcut.ps1"),
        "dev_launcher_exe": os.path.join(root, "launcher", "dist", "DSHLauncher.exe"),
        "dev_icon": os.path.join(root, "launcher", "icon.ico"),
        "dev_make_shortcut_ps1": os.path.join(root, "installer", "make-shortcut.ps1"),
    }


def _pick(res: dict, key: str, dev_key: str | None = None) -> str:
    p = res[key]
    if os.path.exists(p):
        return p
    if dev_key and os.path.exists(res[dev_key]):
        return res[dev_key]
    return p


def _installed_harness_version(harness_dir: str) -> str:
    """The version npm actually put on disk."""
    pkg = os.path.join(harness_dir, "node_modules", "@deepseek-ai", "dsh", "package.json")
    try:
        with open(pkg, encoding="utf-8") as f:
            version = json.load(f).get("version")
        return version if isinstance(version, str) and version else APP_VERSION
    except (OSError, ValueError):
        return APP_VERSION


def _claim_singleton() -> bool:
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind(("127.0.0.1", SINGLETON_PORT))
        s.listen(1)
        return True
    except OSError:
        return False


# --------------------------------------------------------------------------
# install worker
# --------------------------------------------------------------------------
class InstallCancelled(Exception):
    pass


class InstallWorker(threading.Thread):
    def __init__(self, target: str, res: dict, events: "queue.Queue[dict]",
                 cancel: threading.Event, test_mode: bool = False,
                 proxy: str | None = None):
        super().__init__(daemon=True)
        self.target = os.path.abspath(target)
        self.res = res
        self.events = events
        self.cancel = cancel
        self.test_mode = test_mode   # --auto: skip desktop/registry integration
        # `host:port` to route pnpm through, set by preflight when the direct
        # route is unusable but the machine's configured proxy works.
        self.proxy = proxy
        self.log_path = os.path.join(self.target, "install.log")
        self.launcher_dir = os.path.join(self.target, "launcher")
        self.harness_dir = os.path.join(self.target, "harness")
        self.runtime_dir = os.path.join(self.target, "runtime")
        # Filled in once npm tells us what it actually installed; the uninstall
        # entry is written twice — once early so a failed install stays
        # removable, once after the harness lands so the version is real.
        self.app_version = APP_VERSION
        # Result of the link-capability probe, kept so the failure diagnosis can
        # quote it. Empty means the probe never ran (e.g. it failed before the
        # runtime was extracted) — which the diagnosis must not read as FAIL.
        self.links_report: dict = {}
        # Last thing shown on the progress bar, used as "which step failed".
        self._last_progress = ""
        # Set when install.log itself cannot be written, so the failure screen
        # can say so instead of pointing at a file that does not exist.
        self.log_broken = False

    # ---- helpers ----------------------------------------------------------
    def emit(self, kind: str, **kw) -> None:
        if "msg" in kw:
            # Keep the on-screen text and the file in agreement: the log is
            # redacted in log(), so the event payload has to be too.
            kw["msg"] = linkcheck.redact(kw["msg"])
        self.events.put({"kind": kind, **kw})

    def progress(self, pct: float, text: str) -> None:
        self._last_progress = text
        self.emit("progress", pct=pct, text=text)

    def log(self, msg: str) -> None:
        # Redaction happens here, at the single point every line goes through:
        # dsh prints a one-time login URL at startup, and this file is the one
        # the README tells users to send us.
        line = time.strftime("[%H:%M:%S] ") + linkcheck.redact(msg) + "\n"
        try:
            with open(self.log_path, "a", encoding="utf-8") as f:
                f.write(line)
        except OSError:
            self.log_broken = True
            return
        if self.test_mode:
            # --auto reads the log from stdout; the GUI reads the file directly.
            self.emit("log", msg=line.rstrip("\n"))

    def _check_cancel(self) -> None:
        if self.cancel.is_set():
            raise InstallCancelled()

    def _write_env_header(self) -> None:
        """Everything about the machine, before the first byte lands.

        Gives a support reader the run separator (a retry appends to the same
        file, and yesterday's log was five runs run together), the installer's
        own version — which used to appear nowhere in the log at all — and the
        machine facts from _env_facts(). No progress() call here: the
        2/22/24/28/86/92/97/100 sequence stays exactly as it was.
        """
        self.log("=" * 72)
        self.log("run start: DSHSetup %s  %s"
                 % (SETUP_VERSION, time.strftime("%Y-%m-%d %H:%M:%S")))
        for fact in _env_facts(self.target, self.proxy):
            self.log(fact)
        self._check_cancel()

    def _diagnose(self, exc: Exception) -> None:
        """Add what actually went wrong, into the same file.

        The smoke test writes its output to smoke.log, so a support reader used
        to need two files — and had to know the second one existed. Everything
        the rule table needs is already in hand by the time we get here.
        """
        try:
            smoke_path = os.path.join(self.target, "smoke.log")
            exists = os.path.exists(smoke_path)
            smoke = ""
            if exists:
                with open(smoke_path, "rb") as f:
                    smoke = f.read().decode("utf-8", "replace")
            self.log("-- 诊断 " + "-" * 60)
            for line in linkcheck.diagnose(
                    smoke, self.links_report, error=repr(exc),
                    step=self._last_progress, target=self.target,
                    harness_version=self.app_version, smoke_exists=exists):
                self.log(line)
        except Exception:  # noqa: BLE001 - never let diagnosis hide the real error
            self.log("-- 诊断: 生成失败，看上面的错误信息")

    # ---- entry ------------------------------------------------------------
    def run(self) -> None:
        try:
            self._install()
            self.emit("done", ok=True, msg="安装完成")
        except InstallCancelled:
            self.log("安装已取消")
            self.emit("done", ok=False, msg="安装已取消")
        except Exception as exc:  # noqa: BLE001
            self._diagnose(exc)
            self.log("!! 安装失败: %r" % (exc,))
            self.emit("done", ok=False, msg="安装失败: %s" % exc)

    def _install(self) -> None:
        self.progress(2, "正在准备…")
        os.makedirs(self.target, exist_ok=True)
        self._write_env_header()

        # 1) portable node — needed before anything else, npm comes from it
        self.log("解压 Node.js -> %s" % self.runtime_dir)
        self._extract_node(_pick(self.res, "node_zip"), self.runtime_dir, 4, 22,
                           "正在解压 Node.js 运行时…")
        self._check_cancel()

        # 1b) can this machine create links at all? The runtime can answer that
        #     now — same libuv dsh will use — and the 600 MB npm install is
        #     still ahead, so this is the last cheap moment to give up.
        self._probe_links()

        # 2) launcher
        self.progress(24, "正在安装启动器…")
        os.makedirs(self.launcher_dir, exist_ok=True)
        launcher_exe = _pick(self.res, "launcher_exe", "dev_launcher_exe")
        icon = _pick(self.res, "icon", "dev_icon")
        shutil.copy2(launcher_exe, os.path.join(self.launcher_dir, "DSHLauncher.exe"))
        if os.path.exists(icon):
            shutil.copy2(icon, os.path.join(self.launcher_dir, "icon.ico"))
        with open(os.path.join(self.launcher_dir, "harness.txt"), "w", encoding="utf-8") as f:
            f.write(self.harness_dir)
        self.log("launcher installed -> %s" % self.launcher_dir)
        self._check_cancel()

        # 3) uninstaller + registry (before deps, so a failure is still removable)
        self._write_uninstaller()
        if not self.test_mode:
            self._register_uninstall()

        # 4) the harness itself, from npm
        self._install_harness()
        self._check_cancel()
        if not self.test_mode:
            self._register_uninstall()      # now with the real dsh version

        # 5) shortcuts
        if not self.test_mode:
            self.progress(97, "正在创建快捷方式…")
            self._make_shortcuts()
        self.progress(100, "完成")
        self.log("install complete: %s" % self.target)

    # ---- extraction -------------------------------------------------------
    def _extract_node(self, zip_path: str, dest: str, p0: float, p1: float, label: str) -> None:
        if not os.path.exists(zip_path):
            raise RuntimeError("缺少安装负载: %s" % zip_path)
        tmp = dest + ".tmp"
        shutil.rmtree(tmp, ignore_errors=True)
        os.makedirs(tmp, exist_ok=True)
        try:
            with zipfile.ZipFile(zip_path) as zf:
                names = zf.namelist()
                total = len(names)
                for i, name in enumerate(names):
                    self._check_cancel()
                    if i % 150 == 0:
                        self.progress(p0 + (p1 - p0) * i / max(total, 1),
                                      "%s (%d/%d)" % (label, i, total))
                    try:
                        zf.extract(name, tmp)
                    except OSError:
                        pass
            inner = [d for d in os.listdir(tmp) if os.path.isdir(os.path.join(tmp, d))]
            src = os.path.join(tmp, inner[0]) if len(inner) == 1 else tmp
            shutil.rmtree(dest, ignore_errors=True)
            shutil.move(src, dest)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        self.progress(p1, label)

    # ---- dependencies -----------------------------------------------------
    def _node_exe(self) -> str:
        return os.path.join(self.runtime_dir, "node.exe")

    def _probe_links(self) -> None:
        """Can this machine create the links dsh needs? Last cheap moment to ask.

        dsh builds its profile module fallbacks with `symlinkSync(..., "junction")`
        — reparse points, no privilege, no elevation, no Developer Mode. A
        machine where that fails cannot run dsh no matter how the install is
        performed, and finding out here costs a second instead of the two
        minutes and 600 MB the npm install would spend first.

        A probe that could not run is never treated as a failure: UNKNOWN means
        we did not learn anything, which is not the same as learning something
        bad.
        """
        report = linkcheck.probe(self._node_exe(), self.target, cancel=self.cancel)
        self.links_report = report
        self.log(linkcheck.render(report))
        if report.get("status") == "cancelled":
            self._check_cancel()
        if report.get("status") != "ran":
            self.log("链接能力没能测出来（%s）——按未知处理，继续安装。"
                     % (report.get("reason") or "?"))
        message = linkcheck.blocking_message(report)
        if message is not None:
            raise RuntimeError(message)

    def _npm_env(self) -> dict:
        env = dict(os.environ)
        env["PATH"] = self.runtime_dir + os.pathsep + env.get("PATH", "")
        if self.proxy:
            # npm reads proxies from the environment, never from the Windows
            # "Internet Options" proxy that preflight found this in.
            url = "http://" + self.proxy
            for name in ("HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"):
                env[name] = url
            env["NO_PROXY"] = "localhost,127.0.0.1"
            env["no_proxy"] = "localhost,127.0.0.1"
        return env

    def _run_streamed(self, cmd: list[str], cwd: str, env: dict) -> int:
        """Run `cmd`, tee its output into install.log, honour cancellation."""
        self.log("$ %s" % " ".join(cmd))
        proc = subprocess.Popen(
            cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            env=env, shell=False,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0) | getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0),
        )
        assert proc.stdout is not None
        try:
            for raw in proc.stdout:
                try:
                    self.log(raw.decode("utf-8", "replace").rstrip("\n"))
                except OSError:
                    pass
                if self.cancel.is_set():
                    subprocess.run([_SYS32("taskkill.exe"), "/PID", str(proc.pid), "/T", "/F"],
                                   capture_output=True, creationflags=0x08000000)
                    raise InstallCancelled()
        finally:
            proc.stdout.close()
        return proc.wait()

    def _npm_cli(self) -> str:
        """npm's entry script inside the portable runtime."""
        return os.path.join(self.runtime_dir, "node_modules", "npm", "bin", "npm-cli.js")

    def _install_harness(self) -> None:
        """Install `@deepseek-ai/dsh` from npm into <target>\\harness.

        `--ignore-scripts` is deliberate, not a shortcut: upstream's packages
        ship prebuilt binaries for every platform, so nothing needs compiling,
        while node-pty's install script is `prebuild.js || node-gyp rebuild` —
        letting it run risks demanding Visual Studio C++ on a machine that has
        none. The smoke test after this is what makes that bet safe.
        """
        node, npm = self._node_exe(), self._npm_cli()
        if not os.path.exists(node):
            raise RuntimeError("便携版 node.exe 缺失: %s" % node)
        if not os.path.exists(npm):
            raise RuntimeError("便携版 Node 缺少 npm: %s" % npm)
        os.makedirs(self.harness_dir, exist_ok=True)

        reused = self._reuse_harness()
        if reused is not None:
            # A retry after a failure that had nothing to do with the download
            # (a link the machine refuses to create, a backend that would not
            # start) must not pay 2 minutes and 600 MB again.
            self.progress(28, "已装好 dsh 本体 v%s，跳过下载…" % reused)
            self.log("reusing harness v%s（%s；要重装请先运行 uninstall.bat）"
                     % (reused, os.path.join(self.harness_dir, MARKER_NAME)))
        else:
            spec = "%s@%s" % (HARNESS_NPM_NAME, HARNESS_NPM_TAG)
            self.progress(28, "正在从 npm 安装 dsh 本体（约 600 MB，1~3 分钟）…")
            code = self._run_streamed(
                [node, npm, "install", "--no-audit", "--no-fund",
                 "--ignore-scripts", "--loglevel=warn", spec],
                self.harness_dir, self._npm_env())
            if code != 0:
                raise RuntimeError("dsh 安装失败 (exit %d)，详见 %s" % (code, self.log_path))
            self._check_cancel()

        entry = os.path.join(self.harness_dir, "node_modules", "@deepseek-ai", "dsh",
                             "lib", "bin.js")
        if not os.path.exists(entry):
            raise RuntimeError("装完了但找不到 %s" % entry)
        self.app_version = _installed_harness_version(self.harness_dir)
        self.log("harness installed: v%s -> %s" % (self.app_version, entry))
        self._write_install_marker()
        self._smoke_test()

    def _reuse_harness(self) -> str | None:
        """The version already on disk, if a previous run completed npm install.

        The completion marker is what makes this safe. A package.json alone
        proves nothing: cancelling npm halfway leaves one with the right version
        and half the dependency tree, and reusing that would pin a broken
        install that no retry could repair. Only MARKER_NAME — written after npm
        exited 0 *and* the entry point was found — can claim completion.

        No `npm view` freshness check on purpose: it would spend a network round
        trip to decide not to use the network, on exactly the machines whose
        network is the reason they are retrying.
        """
        try:
            with open(os.path.join(self.harness_dir, MARKER_NAME), encoding="utf-8") as f:
                marked = json.load(f).get("version")
        except (OSError, ValueError):
            return None
        if not isinstance(marked, str) or not marked or marked == APP_VERSION:
            return None
        installed = _installed_harness_version(self.harness_dir)
        if installed != marked:
            return None
        entry = os.path.join(self.harness_dir, "node_modules", "@deepseek-ai", "dsh",
                             "lib", "bin.js")
        return installed if os.path.exists(entry) else None

    def _write_install_marker(self) -> None:
        try:
            with open(os.path.join(self.harness_dir, MARKER_NAME), "w", encoding="utf-8") as f:
                json.dump({"version": self.app_version,
                           "ts": time.strftime("%Y-%m-%d %H:%M:%S")}, f)
        except OSError:
            pass

    def _smoke_test(self) -> None:
        """Start the harness once and confirm it serves before calling this done.

        Installing is not the same as running. This is also what makes
        `@latest` + `--ignore-scripts` a safe pair: a broken upstream release
        fails here, in front of the user, instead of the first time they press
        启动.
        """
        node = self._node_exe()
        entry = os.path.join(self.harness_dir, "node_modules", "@deepseek-ai", "dsh",
                             "lib", "bin.js")
        port = 3198                      # deliberately not 3080: don't fight a running install
        self.progress(86, "正在试运行…")
        log_file = os.path.join(self.target, "smoke.log")
        info = subprocess.STARTUPINFO()
        info.dwFlags |= subprocess.STARTF_USESHOWWINDOW
        try:
            log = open(log_file, "wb", buffering=0)
        except OSError:
            log = None
        try:
            proc = subprocess.Popen(
                [node, entry, "web", "--no-open", "--port", str(port)],
                cwd=self.harness_dir, stdout=log, stderr=log, startupinfo=info,
                creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0), shell=False)
        except Exception as exc:  # noqa: BLE001
            if log is not None:
                log.close()
            raise RuntimeError("试运行启动失败: %s" % exc) from exc

        deadline = time.time() + 120
        url = ""
        try:
            while time.time() < deadline:
                self._check_cancel()
                if proc.poll() is not None:
                    raise RuntimeError("试运行时进程退出了 (exit %s)，详见 %s"
                                       % (proc.returncode, log_file))
                try:
                    with open(log_file, "rb") as f:
                        text = f.read().decode("utf-8", "replace")
                    match = re.search(r"dsh web:\s*(http://127\.0\.0\.1:\d+/\?token=[\w.\-]+)",
                                      text)
                    if match:
                        url = match.group(1)
                        break
                except OSError:
                    pass
                time.sleep(0.5)
        finally:
            subprocess.run([_SYS32("taskkill.exe"), "/PID", str(proc.pid), "/T", "/F"],
                           capture_output=True, creationflags=0x08000000)
            if log is not None:
                log.close()
        if not url:
            raise RuntimeError("试运行 120 秒内没有拿到登录令牌，详见 %s" % log_file)
        self.log("试运行通过: %s" % url)
        self.progress(92, "试运行通过")
        try:
            os.remove(log_file)
        except OSError:
            pass

    # ---- uninstaller / registry ------------------------------------------
    def _write_uninstaller(self) -> None:
        """Generate uninstall.bat (pure ASCII). cmd.exe does NOT collapse %%
        outside FOR loops, so batch-parameter expansions use a single % and
        FOR loop variables use %%; the batch deletes itself last via a
        detached process to avoid killing the running script."""
        bat = os.path.join(self.target, "uninstall.bat")
        lines = [
            "@echo off",
            "rem DSH uninstaller (generated by DSH Setup)",
            "setlocal",
            'set "DIR=%~dp0"',
            'if "%DIR:~-1%"=="\\" set "DIR=%DIR:~0,-1%"',
            "rem Refuse to run anywhere that is not a DSH install. The last",
            "rem steps remove every subdirectory of %~dp0 and then the",
            "rem directory itself, so a wrong location here is destructive.",
            'if not exist "%~dp0launcher\\DSHLauncher.exe" if not exist "%~dp0harness" if not exist "%~dp0runtime" (',
            "  echo This does not look like a DSH install directory:",
            "  echo   %~dp0",
            "  echo Nothing was deleted.",
            "  pause",
            "  exit /b 1",
            ")",
            "echo Stopping DSH and the backend...",
            "taskkill /F /IM DSHLauncher.exe >nul 2>&1",
            'for /f "tokens=5" %%%%p in (\'netstat -ano ^| findstr ":%d" ^| findstr "LISTENING"\') do taskkill /F /PID %%%%p >nul 2>&1' % WEB_PORT,
            "echo Removing shortcuts...",
            'if exist "%~dp0shortcuts.txt" for /f "usebackq delims=" %%L in ("%~dp0shortcuts.txt") do del /q "%%L" >nul 2>&1',
            'del /q "%USERPROFILE%\\Desktop\\DSH*.lnk" >nul 2>&1',
            'if defined OneDrive del /q "%OneDrive%\\Desktop\\DSH*.lnk" >nul 2>&1',
            # Both names: the Start Menu folder was "DeepSeek Harness" up to
            # 1.5.1, and leaving it behind would strand an empty folder for
            # anyone upgrading.
            'rmdir /s /q "%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\DeepSeek Harness" >nul 2>&1',
            'rmdir /s /q "%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\DSH" >nul 2>&1',
            "echo Removing registry entry...",
            'reg delete "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\DeepSeekHarness" /f >nul 2>&1',
            "echo Removing install directory...",
            'for /f "delims=" %%F in (\'dir /b /a-d "%~dp0"\') do if /i not "%%F"=="uninstall.bat" del /q "%~dp0%%F" >nul 2>&1',
            'for /d %%D in ("%~dp0*") do rmdir /s /q "\\\\?\\%%~fD" >nul 2>&1',
            "echo Uninstall finished.",
            "pause",
            'start "" /b cmd /c rmdir /s /q "\\\\?\\%DIR%" >nul 2>&1',
            'del "%~f0" >nul 2>&1',
        ]
        with open(bat, "w", encoding="ascii") as f:
            f.write("\r\n".join(lines) + "\r\n")
        self.log("uninstaller written -> %s" % bat)

    def _register_uninstall(self) -> None:
        key = r"HKCU\Software\Microsoft\Windows\CurrentVersion\Uninstall\DeepSeekHarness"
        bat = os.path.join(self.target, "uninstall.bat")
        exe = os.path.join(self.launcher_dir, "DSHLauncher.exe")
        vals = [
            ("DisplayName", 'DSH'),
            ("DisplayVersion", self.app_version),
            ("Publisher", "DeepSeek AI"),
            ("InstallLocation", self.target),
            ("DisplayIcon", '"%s,0"' % exe),
            ("UninstallString", 'cmd.exe /c ""%s""' % bat),
        ]
        for name, val in vals:
            subprocess.run([_SYS32("reg.exe"), "add", key, "/f", "/v", name, "/d", val],
                           capture_output=True, creationflags=0x08000000)
        for name in ("NoModify", "NoRepair"):
            subprocess.run([_SYS32("reg.exe"), "add", key, "/f", "/v", name, "/t", "REG_DWORD", "/d", "1"],
                           capture_output=True, creationflags=0x08000000)

    # ---- shortcuts --------------------------------------------------------
    def _desktop_dir(self) -> str:
        try:
            out = subprocess.run(
                [_POWERSHELL(), "-NoProfile", "-Command", "[Environment]::GetFolderPath('Desktop')"],
                capture_output=True, text=True, creationflags=0x08000000, timeout=20)
            p = out.stdout.strip()
            if p and os.path.isdir(p):
                return p
        except Exception:
            pass
        return os.path.join(os.path.expanduser("~"), "Desktop")

    def _make_shortcuts(self) -> None:
        ps1 = _pick(self.res, "make_shortcut_ps1", "dev_make_shortcut_ps1")
        if not os.path.exists(ps1):
            raise RuntimeError("缺少 make-shortcut.ps1")
        exe = os.path.join(self.launcher_dir, "DSHLauncher.exe")
        # Point the shortcut at the exe's own icon: a self-update swaps the
        # exe but not a loose .ico, so an icon.ico path would go stale.
        icon = exe
        desc = "DSH：启动后端 / 打开网页 / 关闭 / 最小化到托盘"
        lnks = [
            os.path.join(self._desktop_dir(), LAUNCHER_DISPLAY + ".lnk"),
        ]
        start_menu = os.path.join(os.environ.get("APPDATA", ""), "Microsoft", "Windows",
                                  "Start Menu", "Programs", "DSH")
        try:
            os.makedirs(start_menu, exist_ok=True)
            lnks.append(os.path.join(start_menu, LAUNCHER_DISPLAY + ".lnk"))
        except OSError:
            pass
        for lnk in lnks:
            self._run_powershell_script(ps1, [
                "-LnkPath", lnk,
                "-TargetPath", exe,
                "-IconPath", icon,
                "-WorkingDirectory", self.launcher_dir,
                "-Description", desc,
            ])
        self.shortcuts = lnks
        # precise list for the uninstaller (ANSI, so cmd reads it under the
        # same locale it was written on)
        try:
            with open(os.path.join(self.target, "shortcuts.txt"), "w", encoding="mbcs") as f:
                f.write("\n".join(lnks))
        except OSError:
            pass

    def _run_powershell_script(self, script: str, args: list[str]) -> None:
        cmd = [_POWERSHELL(), "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", script] + args
        r = subprocess.run(cmd, capture_output=True, text=True,
                           creationflags=0x08000000, timeout=60)
        if r.returncode != 0:
            self.log("shortcut 失败(%d): %s" % (r.returncode, r.stderr.strip()))


# --------------------------------------------------------------------------
# CLI / auto mode (used by the build script and CI-style self-checks)
# --------------------------------------------------------------------------
def _run_auto(argv: list[str]) -> int:
    target = "."
    if "--dir" in argv:
        target = argv[argv.index("--dir") + 1]
    res = resources()

    proxy = None
    if "--skip-preflight" not in argv:
        report = preflight.run(os.path.abspath(target))
        for c in report.checks:
            _say("CHECK %-4s %-14s %s" % (c.status.upper(), c.key, c.detail))
            if c.hint:
                # The actionable half of a check used to be dropped here.
                _say("      hint: %s" % c.hint)
        _say("PREFLIGHT %s" % ("ok" if report.ok else "blocked"))
        if not report.ok:
            return 1
        proxy = report.proxy

    events: "queue.Queue[dict]" = queue.Queue()
    cancel = threading.Event()
    worker = InstallWorker(target, res, events, cancel, test_mode=True, proxy=proxy)
    worker.start()
    last_pct = 0
    while True:
        try:
            ev = events.get(timeout=0.25)
        except queue.Empty:
            # Only give up once the queue is empty *and* the worker is gone:
            # testing is_alive() first can drop the `done` event (and exit 1 on
            # a successful install) whenever the worker finishes between the two.
            if not worker.is_alive():
                return 1
            continue
        if ev["kind"] == "progress":
            pct = int(ev["pct"])
            if pct != last_pct:
                last_pct = pct
                _say("PROGRESS %3d%%  %s" % (pct, ev["text"]))
        elif ev["kind"] == "log":
            _say("  %s" % ev["msg"])
        elif ev["kind"] == "done":
            _say("DONE ok=%s msg=%s" % (ev["ok"], ev["msg"]))
            return 0 if ev["ok"] else 1


