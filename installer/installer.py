def _SYS32(name: str) -> str:
    """Absolute path to a Windows system tool.

    Bare names resolve through PATH, so a directory earlier in PATH wins — a
    trivial way to make this program execute somebody else's taskkill.exe.
    Nothing here needs that risk; the path is always the same.
    """
    root = os.environ.get("SystemRoot") or r"C:\Windows"
    return os.path.join(root, "System32", name)



def _POWERSHELL() -> str:
    """Absolute path to Windows PowerShell (it is not directly in System32)."""
    root = os.environ.get("SystemRoot") or r"C:\Windows"
    return os.path.join(root, "System32", "WindowsPowerShell", "v1.0", "powershell.exe")




APP_NAME = "DSH"
# The harness is installed from npm — upstream publishes prebuilt packages there
# and nothing at all on GitHub releases, and their own documented install is
# `npx @deepseek-ai/dsh web`. Installing the published package takes about a
# minute and needs no source checkout, no pnpm and no compiler, where the old
# source-and-build flow took 10~25 minutes and 4~5 GB.
HARNESS_NPM_NAME = "@deepseek-ai/dsh"
# Resolved at install time rather than pinned: upstream's `latest` is their own
# statement of which version a new user should get, and following it means a
# shipped DSHSetup.exe does not go stale. The smoke test below is what makes
# that safe.
HARNESS_NPM_TAG = "latest"
# Fallback for the uninstall entry before the real version is known.
APP_VERSION = "unknown"
LAUNCHER_DISPLAY = "DSH"
WEB_PORT = 3080
SINGLETON_PORT = 3199
# Written into harness\ only after npm exited 0 and the entry point was found.
# Its whole job is to make "reuse what is already on disk" safe: a bare
# package.json proves nothing, because a cancelled npm install leaves one behind
# with the right version and half the dependency tree.
MARKER_NAME = ".dsh-installed.json"


def _is_elevated() -> bool:
    """Whether this process holds an elevated admin token.

    Cheap and process-local — no subprocess like `whoami`, which under a
    security product's hooking costs a noticeable moment on every install.
    """
    try:
        import ctypes
        return bool(ctypes.windll.shell32.IsUserAnAdmin())
    except Exception:  # noqa: BLE001 - never let diagnostics break an install
        return False


def _env_facts(target: str, proxy: str | None = None) -> list[str]:
    """The machine facts worth having in any log a user sends us.

    Shared by the install log header and by `--diag`, so a report and an install
    log can never disagree about the same machine.

    Deliberately absent: SeCreateSymbolicLinkPrivilege. dsh links its profile
    fallbacks with junctions, which need no privilege at all, so printing
    "priv: no" into a block users forward to us would teach the wrong lesson —
    that is exactly the red herring this release exists to kill.
    """
    profile = os.environ.get("USERPROFILE") or ""
    try:
        ver = sys.getwindowsversion()
        os_name = "Windows %d.%d build %d %s" % (ver.major, ver.minor, ver.build,
                                                 platform.machine())
    except AttributeError:  # pragma: no cover - non-Windows
        os_name = platform.platform()
    try:
        # Walk up first: the install directory usually does not exist yet.
        free_gb = "%.1f GB free" % (shutil.disk_usage(linkcheck.existing_ancestor(target)).free
                                    / (1024.0 ** 3))
    except OSError:
        free_gb = "unknown"
    return [
        "target: %s" % target,
        "os: %s" % os_name,
        "account: %s" % (os.environ.get("USERNAME") or "?"),
        "dsh home: %s" % (os.path.join(profile, ".dsh") if profile else "?"),
        "elevated: %s" % ("yes" if _is_elevated() else "no"),
        "developer mode: %s (affects symlinks only - dsh uses junctions)"
        % ("on" if preflight.dev_mode_enabled() else "off"),
        "disk: %s" % free_gb,
        "proxy: %s" % (proxy or "none"),
        "setup exe: %s" % (sys.executable if getattr(sys, "frozen", False)
                           else os.path.abspath(__file__)),
    ]


def _say(text: str) -> None:
    """print() that cannot kill a headless run.

    stdout is None in a windowed frozen exe, and on a Chinese Windows it is
    cp936 as soon as it is redirected — one character outside that code page
    (an arrow, a check mark) would otherwise abort the install halfway through.
    """
    out = sys.stdout
    if out is None:
        return
    try:
        print(text, flush=True)
    except UnicodeEncodeError:
        enc = getattr(out, "encoding", None) or "ascii"
        out.write(text.encode(enc, "replace").decode(enc, "replace") + "\n")
        out.flush()


